package conditions;

public class Marks {

	public static void main(String[] args) {
		int n=99;
		if(n<=90 & n>=100) {
			System.out.println("a");
		}else if(n<=80 & n>=89) {
			System.out.println("b");
		}else if(n<=70 & n>=79) {
			System.out.println("c");
		}else if(n<=60 & n>=69) {
			System.out.println("d");
		}else if(n<=50 & n>=59) {
			System.out.println("e");
		}else{
			System.out.println("f");
		}

	}

}
